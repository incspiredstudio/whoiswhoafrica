"""Builds brand mark files and the home stage masks (REQ-052, REQ-273, D-073).

1. For each PNG given (from render.cjs), writes wp-content/themes/whoiswho-child/assets/brand/mark-<name>.webp:
   600 x 600, black on transparent, the drawing trimmed and fitted into a centred 520 px box.
2. Rewrites wp-content/themes/whoiswho/assets/js/stage/marks.js from the four approved mark files: each mark trimmed,
   fitted into 200 px, centred on a 220 px grid, one bit per pixel (least significant bit first), base64.

Run from site/ (needs Python 3 and Pillow):
    node build/marks/render.cjs <tmp>
    python build/marks/build-marks.py <tmp>/pyramid.png <tmp>/shield.png
Then run build/pattern-tile.py to rebuild the pattern tile.
"""

import base64
import json
import sys
from pathlib import Path

from PIL import Image

SITE = Path(__file__).resolve().parent.parent.parent
BRAND = SITE / "wp-content" / "themes" / "whoiswho-child" / "assets" / "brand"
STAGE = SITE / "wp-content" / "themes" / "whoiswho" / "assets" / "js" / "stage" / "marks.js"
MARKS = ["cowrie", "lion", "shield", "pyramid"]


def fit(alpha: Image.Image, size: int, box: int) -> Image.Image:
    """The alpha channel trimmed to its drawing and fitted, centred, into box px on a size px canvas."""
    alpha = alpha.crop(alpha.getbbox())
    scale = box / max(alpha.size)
    alpha = alpha.resize((round(alpha.width * scale), round(alpha.height * scale)), Image.LANCZOS)
    out = Image.new("L", (size, size), 0)
    out.paste(alpha, ((size - alpha.width) // 2, (size - alpha.height) // 2))
    return out


def write_mark(png: Path) -> None:
    alpha = fit(Image.open(png).convert("RGBA").getchannel("A"), 600, 520)
    mark = Image.new("RGBA", (600, 600), (0, 0, 0, 0))
    mark.putalpha(alpha)
    mark.save(BRAND / f"mark-{png.stem}.webp", lossless=True, method=6)


def stage_mask(name: str) -> dict:
    alpha = fit(Image.open(BRAND / f"mark-{name}.webp").convert("RGBA").getchannel("A"), 220, 200)
    w, h = alpha.size
    bits = bytearray((w * h + 7) // 8)
    px = alpha.load()
    for y in range(h):
        for x in range(w):
            if px[x, y] >= 128:
                i = y * w + x
                bits[i >> 3] |= 1 << (i & 7)
    return {"w": w, "h": h, "d": base64.b64encode(bytes(bits)).decode("ascii")}


if __name__ == "__main__":
    for arg in sys.argv[1:]:
        write_mark(Path(arg))
    masks = {name: stage_mask(name) for name in MARKS}
    STAGE.write_text(
        "/* The four brand marks (cowrie, lion, shield, pyramid) as 1-bit masks, sampled by the home page particle stage."
        " Generated by site/build/marks/build-marks.py; do not edit. */\n"
        f"export const MARKS = {json.dumps(masks, separators=(',', ':'))};\n",
        encoding="utf-8",
    )
