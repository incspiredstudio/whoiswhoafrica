<#
Local environment without Docker (WordPress Studio). Run from site/:  powershell -File deploy/local/setup.ps1
Creates a Studio site in site/.studio (git-ignored), links our code into it, activates the child theme.
The Administrator password is generated by Studio and printed once; nothing is committed.
#>
$ErrorActionPreference = "Stop"
$site = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
$studio = if (Get-Command studio -ErrorAction SilentlyContinue) { "studio" } else { Join-Path $env:LOCALAPPDATA "studio_app\bin\studio.bat" }
$dir = Join-Path $site ".studio"
if (-not (Test-Path (Join-Path $dir "wp-content"))) {
  & $studio create --path $dir --name whoiswho --php 8.3 --file-access all-files --skip-browser
}
$links = @{
  "plugins\whoiswho-core"  = "wp-content\plugins\whoiswho-core"
  "themes\whoiswho"        = "wp-content\themes\whoiswho"
  "themes\whoiswho-child"  = "wp-content\themes\whoiswho-child"
}
foreach ($k in $links.Keys) {
  $target = Join-Path (Join-Path $dir "wp-content") $k
  if (-not (Test-Path $target)) { New-Item -ItemType Junction -Path $target -Target (Join-Path $site $links[$k]) | Out-Null }
}
& $studio start --path $dir --skip-browser
try { & $studio wp --path $dir theme activate whoiswho-child } catch { Write-Warning "Child theme not installable yet (its files arrive with the theme issues)." }
& $studio wp --path $dir rewrite structure "/%postname%/"
& $studio status --path $dir
