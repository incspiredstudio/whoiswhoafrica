#!/usr/bin/env node
// Traceability generator (REQ-056): every requirement with its issues, pull requests and tests, so the verify step can prove
// nothing was missed. Reads docs/requirements.md, docs/plan/*.json (+ issue-map.json), the test names under site/tests (PHPUnit
// `test_REQ_<n>_...`, Playwright and node specs that cite `REQ-<n>` in a title) and, optionally, merged pull request bodies.
// Writes docs/traceability.md. The output has no timestamps, so the same inputs give the same file.
//
//   node scripts/traceability.js                      write docs/traceability.md
//   node scripts/traceability.js --out FILE           write somewhere else
//   node scripts/traceability.js --prs prs.json       add pull requests (gh pr list --state merged --json number,title,body)
//   node scripts/traceability.js --fetch-prs          fetch merged pull requests with the gh CLI
//   node scripts/traceability.js --strict             exit 1 when there are problems (report-only by default; blocking from M5)
//   node --test scripts/__tests__/traceability.test.js   run the self tests

const fs = require("fs");
const path = require("path");
const { execSync } = require("child_process");

const root = path.join(__dirname, "..");

const pad = (n) => String(n).padStart(3, "0");
const reqId = (n) => "REQ-" + pad(n);

/** Requirements: [{ id, withdrawn }] from the table in docs/requirements.md. */
function parseRequirements(text) {
  const out = new Map();
  for (const line of text.split(/\r?\n/)) {
    const m = line.match(/^\|\s*(REQ-\d{3})\s*\|(.*)$/);
    if (!m) continue;
    const withdrawn = /\*\*WITHDRAWN/i.test(m[2]) || /\|\s*Withdrawn\s*\|/i.test(m[2]);
    out.set(m[1], { id: m[1], withdrawn });
  }
  return out;
}

/** Plan issues: [{ key, title, reqs, number }] from the milestone JSON files and the issue map. */
function parsePlan(files, issueMap) {
  const issues = [];
  for (const text of files) {
    const data = JSON.parse(text);
    for (const issue of data.issues || []) {
      issues.push({ key: issue.key, title: issue.title || "", reqs: issue.reqs || [], number: issueMap[issue.key] || null });
    }
  }
  return issues;
}

/** Tests: [{ req, name, file }] from file texts. PHPUnit names carry the REQ; specs cite it in a title. */
function scanTestFile(file, text) {
  const found = [];
  if (file.endsWith(".php")) {
    for (const m of text.matchAll(/function\s+(test_REQ_(\d+)_\w*)/g)) found.push({ req: reqId(m[2]), name: m[1], file });
  } else {
    for (const m of text.matchAll(/\b(?:test|it|describe)(?:\.\w+)?\(\s*(["'`])((?:(?!\1).)*)\1/g)) {
      for (const r of m[2].matchAll(/REQ-(\d+)/g)) found.push({ req: reqId(r[1]), name: m[2], file });
    }
  }
  return found;
}

/** Pull requests: [{ number, title, reqs }] from gh output. */
function parsePrs(list) {
  return list.map((pr) => ({
    number: pr.number,
    title: pr.title || "",
    reqs: [...new Set([...((pr.body || "") + " " + (pr.title || "")).matchAll(/REQ-(\d+)/g)].map((m) => reqId(m[1])))],
  }));
}

/** Pure: build the report model and the problems. */
function build({ requirements, issues, tests, prs }) {
  const rows = new Map();
  for (const req of requirements.values()) rows.set(req.id, { ...req, issues: [], prs: [], tests: [] });
  const problems = { issuesCitingBadReq: [], testsCitingBadReq: [], withoutTest: [] };

  for (const issue of issues) {
    for (const r of issue.reqs) {
      const row = rows.get(r);
      if (!row) problems.issuesCitingBadReq.push(`${issue.key} cites ${r}, which does not exist`);
      else if (row.withdrawn) problems.issuesCitingBadReq.push(`${issue.key} cites the withdrawn ${r}`);
      if (row) row.issues.push(issue);
    }
  }
  for (const pr of prs) for (const r of pr.reqs) if (rows.has(r)) rows.get(r).prs.push(pr);
  for (const t of tests) {
    const row = rows.get(t.req);
    if (!row) problems.testsCitingBadReq.push(`${t.name} (${t.file}) cites ${t.req}, which does not exist`);
    else if (row.withdrawn) problems.testsCitingBadReq.push(`${t.name} (${t.file}) cites the withdrawn ${t.req}`);
    if (row) row.tests.push(t);
  }
  for (const row of rows.values()) if (!row.withdrawn && row.tests.length === 0) problems.withoutTest.push(row.id);
  for (const list of Object.values(problems)) list.sort();
  return { rows, problems };
}

const MAX_TESTS_SHOWN = 4;

/** Pure: markdown for a model. */
function render({ rows, problems }) {
  const all = [...rows.values()].sort((a, b) => a.id.localeCompare(b.id));
  const live = all.filter((r) => !r.withdrawn);
  const tested = live.filter((r) => r.tests.length > 0).length;
  const out = [];
  out.push("# Traceability: requirement to issue, pull request and test");
  out.push("");
  out.push("<!-- Generated by scripts/traceability.js. Do not edit by hand: run `node scripts/traceability.js`. -->");
  out.push("");
  out.push(`Requirements: ${all.length} (${live.length} live, ${all.length - live.length} withdrawn). Live requirements with a test: ${tested} of ${live.length}.`);
  out.push("");
  out.push("## Problems");
  out.push("");
  const sections = [
    ["Tests or issues citing a withdrawn or missing requirement", [...problems.testsCitingBadReq, ...problems.issuesCitingBadReq]],
    ["Live requirements with no test yet", problems.withoutTest],
  ];
  for (const [title, list] of sections) {
    out.push(`### ${title} (${list.length})`);
    out.push("");
    if (list.length === 0) out.push("None.");
    else if (title.startsWith("Live")) out.push(list.join(", "));
    else for (const p of list) out.push("- " + p);
    out.push("");
  }
  out.push("## Matrix");
  out.push("");
  out.push("| Requirement | Status | Issues | Pull requests | Tests |");
  out.push("|---|---|---|---|---|");
  for (const row of all) {
    const issues = [...new Set(row.issues.map((i) => (i.number ? `${i.key} (#${i.number})` : i.key)))].sort().join(", ") || "-";
    const prs = [...new Set(row.prs.map((p) => "#" + p.number))].sort((a, b) => Number(a.slice(1)) - Number(b.slice(1))).join(", ") || "-";
    const names = [...new Set(row.tests.map((t) => t.name))].sort();
    const shown = names.slice(0, MAX_TESTS_SHOWN).map((n) => "`" + n.replace(/\|/g, "\\|") + "`").join("<br>");
    const more = names.length > MAX_TESTS_SHOWN ? `<br>and ${names.length - MAX_TESTS_SHOWN} more` : "";
    out.push(`| ${row.id} | ${row.withdrawn ? "withdrawn" : "live"} | ${issues} | ${prs} | ${shown ? shown + more : "-"} |`);
  }
  out.push("");
  return out.join("\n");
}

function walk(dir, accept, acc = []) {
  if (!fs.existsSync(dir)) return acc;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (!["node_modules", "vendor", "dist"].includes(entry.name)) walk(full, accept, acc);
    } else if (accept(entry.name)) acc.push(full);
  }
  return acc;
}

/** Read everything from a repo folder. */
function load(repo, prList) {
  const requirements = parseRequirements(fs.readFileSync(path.join(repo, "docs/requirements.md"), "utf8"));
  const planDir = path.join(repo, "docs/plan");
  const mapFile = path.join(planDir, "issue-map.json");
  const issueMap = fs.existsSync(mapFile) ? JSON.parse(fs.readFileSync(mapFile, "utf8")) : {};
  const planFiles = fs.readdirSync(planDir).filter((f) => /^M\d.*\.json$/.test(f)).sort().map((f) => fs.readFileSync(path.join(planDir, f), "utf8"));
  const tests = [];
  const testFiles = [
    ...walk(path.join(repo, "site/tests"), (n) => /Test\.php$|\.spec\.ts$/.test(n)),
    ...walk(path.join(repo, "scripts/__tests__"), (n) => /\.test\.js$/.test(n)),
  ];
  for (const file of testFiles) tests.push(...scanTestFile(path.relative(repo, file).replace(/\\/g, "/"), fs.readFileSync(file, "utf8")));
  return { requirements, issues: parsePlan(planFiles, issueMap), tests, prs: parsePrs(prList || []) };
}

module.exports = { parseRequirements, parsePlan, scanTestFile, parsePrs, build, render, load };

if (require.main === module) {
  const args = process.argv.slice(2);
  const opt = (name) => (args.includes(name) ? args[args.indexOf(name) + 1] : null);
  let prs = [];
  if (opt("--prs")) prs = JSON.parse(fs.readFileSync(opt("--prs"), "utf8"));
  else if (args.includes("--fetch-prs")) prs = JSON.parse(execSync("gh pr list --state merged --limit 1000 --json number,title,body", { cwd: root, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 }));
  const model = build(load(root, prs));
  const out = opt("--out") || path.join(root, "docs/traceability.md");
  fs.writeFileSync(out, render(model));
  const bad = model.problems.testsCitingBadReq.length + model.problems.issuesCitingBadReq.length;
  console.log(`Wrote ${path.relative(root, out)}: ${model.rows.size} requirements, ${bad} citation problem(s), ${model.problems.withoutTest.length} live requirement(s) without a test.`);
  if (args.includes("--strict") && (bad > 0 || model.problems.withoutTest.length > 0)) process.exit(1);
}
